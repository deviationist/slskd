namespace slskd.Messaging.API
{
    using System.ComponentModel.DataAnnotations;

    /// <summary>
    ///     A room message to take in as though the server had sent it.
    /// </summary>
    public class SimulatedRoomMessageRequest
    {
        /// <summary>
        ///     The room. One not joined is made, and exists only in slskd.
        /// </summary>
        [Required]
        [StringLength(100, MinimumLength = 1)]
        public string RoomName { get; set; }

        /// <summary>
        ///     Who it is from.
        /// </summary>
        [Required]
        [StringLength(100, MinimumLength = 1)]
        public string Username { get; set; }

        /// <summary>
        ///     What they said.
        /// </summary>
        [Required]
        [StringLength(2000, MinimumLength = 1)]
        public string Message { get; set; }
    }
}
