namespace slskd.Transfers;

/// <summary>
///     The order in which a list of transfers is shown.
/// </summary>
/// <remarks>
///     Presentation only. Nothing here changes which transfers exist, what they
///     do, or the order the API returns them in -- it is the default the web UI
///     starts from, which each browser may then override for itself.
/// </remarks>
public enum TransferSortOrder
{
    /// <summary>
    ///     Most recently requested first.
    /// </summary>
    Newest = 0,

    /// <summary>
    ///     Least recently requested first, which is the order the API returns.
    /// </summary>
    Oldest = 1,
}
